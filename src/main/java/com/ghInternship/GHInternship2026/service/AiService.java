package com.ghInternship.GHInternship2026.service;

/**
 * Интерфейс сервиса для взаимодействия с внешними AI-сервисами (LLM API).
 * Обеспечивает безопасное управление API-ключом без риска его утечки.
 */
public interface AiService {

    /**
     * Проверяет, сконфигурирован ли валидный API-ключ для работы с AI-сервисом.
     *
     * @return true, если ключ присутствует и не пуст
     */
    boolean isConfigured();

    /**
     * Возвращает безопасное маскированное строковое представление ключа
     * для безопасного логирования и трассировки (например, sk-***abcd).
     *
     * @return маскированный API-ключ или статус [НЕ ЗАДАН]
     */
    String getMaskedApiKey();

    /**
     * Отправляет текстовый запрос во внешний AI-сервис и возвращает сгенерированный ответ.
     *
     * @param prompt входной промпт пользователя
     * @return текстовый ответ от нейросети
     */
    String generateResponse(String prompt);
}

